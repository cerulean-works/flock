def main() -> None:
    """Write this module again from the installed transformers."""
    import transformers
    from transformers.models.auto.modeling_auto import MODEL_FOR_CAUSAL_LM_MAPPING_NAMES

    path = Path(__file__)
    text = path.read_text()
    head, _, rest = text.partition("CAUSAL_LMS: dict[str, str] = {\n")
    _, _, tail = rest.partition("}\n# fmt: on\n")
    entries = "".join(
        f'    "{name}": "{model}",\n'
        for name, model in sorted(MODEL_FOR_CAUSAL_LM_MAPPING_NAMES.items())
    )
    head = head.replace(
        f'TRANSFORMERS = "{TRANSFORMERS}"', f'TRANSFORMERS = "{transformers.__version__}"'
    )
    path.write_text(f"{head}CAUSAL_LMS: dict[str, str] = {{\n{entries}}}\n# fmt: on\n{tail}")


if __name__ == "__main__":
    main()

"""Write the 750M phase-1 sweep files, their 7.5B early-decay branches, and the probe.

    python make_750m.py

Model: llama3.2-200m preset reshaped to d1280 x 24 layers (20 heads, 4 KV heads, FFN 5120,
tied embeddings). Data, tokenizer, attention (FA4) and compile as in the 400M sweep.
Main runs: 15B tokens, warmup 1% / constant to 80% / linear decay over the last 20%,
beta2 0.99, AdamW lr 3e-3, seed 0, 65536 tokens per GPU (no gradient accumulation).
Saves at 3B, 6B (feeds the branches), 9B, 12B and 15B: a 6 GB save takes ~1.5-3 min on /work, so
recovery saves are every 3B tokens rather than more often.

Branches (`-d7p5b`): start from the parent's 6B checkpoint (constant-LR phase) and train to
7.5B under the same fractional schedule relative to 7.5B, i.e. linear decay 6B -> 7.5B.
A run trains exactly batch_tokens x GPUs tokens per update, so the 6B checkpoint is update
ceil(6e9 / global batch); `sweep plan --check-tokens` confirms it.
"""

import json
import math
from pathlib import Path

ROOT = Path("/work/u4982363/sweeps")
CONFIGS = ROOT / "configs"
PER_GPU = 65536
BATCHES = {  # name: (GPUs per run, Muon LRs, master_port of main sweep, of branch sweep)
    "524k": (8, [0.004, 0.006, 0.008], 32100, 32400),
    "1m": (16, [0.006, 0.008, 0.012], 32200, 32500),
    "2m": (32, [0.008, 0.012, 0.016], 32300, 32600),
}
BRANCH_AT = 6_000_000_000
SCHEDULE = [
    {"start": 0, "end": 0.01, "start_ratio": 0.0, "end_ratio": 1.0},
    {"start": 0.01, "end": 0.8, "start_ratio": 1.0, "end_ratio": 1.0},
    {"start": 0.8, "end": 1.0, "start_ratio": 1.0, "end_ratio": 0.0, "interpolation": "linear"},
]


def base(stop: str, save: list[str], project: str) -> dict:
    return {
        "seed": 0,
        "data": {"text_path": "/work/u4982363/datasets/mix-200b-tc114b-en86b-seed0", "text_version": 1,
                 "block_rows": 2048, "add_bos": True, "add_eos": True, "chunk_length": 4096},
        "model": {"preset": "llama3.2-200m", "attn_implementation": "flash_attention_4",
                  "overrides": {"hidden_size": 1280, "intermediate_size": 5120, "num_hidden_layers": 24,
                                "num_attention_heads": 20, "num_key_value_heads": 4}},
        "optimizer": {"type": "muon_adamw", "lr": 0.003, "betas": [0.9, 0.99], "muon_lr": 0.006},
        "schedule": SCHEDULE,
        # save_steps above any run's length: saves come from save_tokens only.
        "trainer": {"batch_tokens": PER_GPU, "torch_compile": True, "dataloader_num_workers": 8,
                    "dataloader_prefetch_factor": 8, "logging_steps": 10, "save_steps": 10_000_000,
                    "wandb_project": project},
        "stop_tokens": stop,
        "save_tokens": save,
    }


def run(muon_lr: float, **extra) -> dict:
    return {"optimizer.muon_lr": muon_lr, "optimizer.lr": 0.003, "optimizer.betas": [0.9, 0.99],
            "seed": 0, **extra}


def fill(template: str, values: dict) -> str:
    """Render a name template the way the sweep does (checked against `sweep plan`)."""
    for key, value in values.items():
        template = template.replace("{" + key + "}", str(value))
    return template


def write(name: str, doc: dict, header: str) -> None:
    path = CONFIGS / f"{name}.yaml"
    path.write_text(header + json.dumps(doc, indent=2) + "\n")  # JSON is valid YAML.
    print("wrote", path)


for size, (gpus, lrs, port, branch_port) in BATCHES.items():
    name = f"llama750m-bs{size}"
    template = f"{name}-b2{{optimizer.betas}}-mlr{{optimizer.muon_lr}}-alr{{optimizer.lr}}-s{{seed}}"
    main = {
        "sweep": {"name": name, "output_root": str(ROOT), "gpus_per_run": gpus, "master_port": port,
                  "name_template": template, "runs": [run(lr) for lr in lrs]},
        "base": base("15B", ["3B", "6B", "9B", "12B"], "scaling-law-pilot"),
    }
    write(name, main, f"# 750M (d1280 x 24) at batch {size} ({gpus} GB200 x {PER_GPU} tokens), 15B tokens.\n"
          "# Generated by make_750m.py.\n")
    step = math.ceil(BRANCH_AT / (gpus * PER_GPU))
    branches = []
    for lr in lrs:
        parent = fill(template, {"optimizer.betas": "_0.9_0.99_", "optimizer.muon_lr": lr,
                                 "optimizer.lr": 0.003, "seed": 0})
        branches.append(run(lr, branch_from=f"{ROOT}/{name}/runs/{parent}/checkpoints/checkpoint-{step}"))
    branch = {
        "sweep": {"name": f"{name}-d7p5b", "output_root": str(ROOT), "gpus_per_run": gpus,
                  "master_port": branch_port,
                  "name_template": template.replace(name, f"{name}-d7p5b"), "runs": branches},
        "base": base("7.5B", [], "scaling-law-pilot"),
    }
    write(f"{name}-d7p5b", branch, f"# Early-decay branches of {name}: from each parent's 6B checkpoint "
          f"(update {step}),\n# linear decay 6B -> 7.5B (same fractional schedule relative to 7.5B). "
          "Generated by make_750m.py.\n")

# Probe: 1 node x 4 GPUs at 65536 tokens/GPU; then a branch from its 100M checkpoint.
probe_template = "probe-llama750m-4x65k-mlr{optimizer.muon_lr}"
probe = {
    "sweep": {"name": "probe-llama750m-4x65k", "output_root": str(ROOT), "gpus_per_run": 4,
              "master_port": 32900, "name_template": probe_template, "runs": [run(0.006)]},
    "base": base("200M", ["100M"], "scaling-law-pilot-probe"),
}
write("probe-llama750m-4x65k", probe, "# Probe: memory, throughput, loss at 4 GPUs x 65536 tokens.\n")
probe_step = math.ceil(100_000_000 / (4 * PER_GPU))
parent = fill(probe_template, {"optimizer.muon_lr": 0.006})
probe_branch = {
    "sweep": {"name": "probe-llama750m-4x65k-branch", "output_root": str(ROOT), "gpus_per_run": 4,
              "master_port": 32950, "name_template": probe_template + "-branch",
              "runs": [run(0.006, branch_from=f"{ROOT}/probe-llama750m-4x65k/runs/{parent}/checkpoints/checkpoint-{probe_step}")]},
    "base": base("125M", [], "scaling-law-pilot-probe"),
}
write("probe-llama750m-4x65k-branch", probe_branch, "# Probe branch: from the probe's 100M checkpoint, "
      "decay to 125M.\n")
